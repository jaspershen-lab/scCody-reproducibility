from __future__ import annotations
import argparse

def build_common_argument_parser(description: str, method_name: str) -> argparse.ArgumentParser:
    """Build arguments shared by the scNODE and scDiffEq integrations."""
    parser = argparse.ArgumentParser(description=description, fromfile_prefix_chars="@")
    add = parser.add_argument
    add('--normal-h5ad', required=True)
    add('--disease-h5ad', required=True)
    add('--dataset-config', default='', help='Dataset YAML owning the canonical DE reference policy.')
    add('--run-name', default='')
    add('--outdir', default='')
    add('--age-key', default='age')
    add('--development-stage-key', default='development_stage')
    add('--disease-key', default='disease')
    add('--cell-type-key', default='cell_type')
    add('--donor-key', default='donor_id')
    add('--projection-unit', choices=['donor', 'donor_cell_type'], default='donor', help=f"Biological unit for disease/calibration projection. 'donor' is the method-native {method_name} baseline; 'donor_cell_type' enables matched-unit analyses.")
    add('--cell-type-readout', choices=['none', 'pca_knn'], default='none', help='Post-rollout cell-type readout. pca_knn preserves the global source pool, annotates generated cells at every age-grid point, and reports per-cell-type localization.')
    add('--pca-knn-cell-types', default='', help='Comma-separated cell types retained by the PCA-KNN localization readout.')
    add('--layer', default='', help=f'Layer for {method_name} input. Empty uses X.')
    add('--count-layer', default='counts')
    add('--de-method', choices=['edger_pseudobulk', 'logfc', 'none'], default='edger_pseudobulk')
    add('--evaluation-stage', choices=['full', 'localization', 'generation', 'expression_de'], default='full')
    add('--metric-profile', choices=['full', 'hpo_objective'], default='full')
    add('--edger-dir', default='')
    add('--rscript', default='Rscript')
    add('--min-eval-cells-per-ct', type=int, default=50)
    add('--reference-stratify-by', default='', help='Comma-separated obs columns added to age x cell-type evaluation-reference strata.')
    add('--checkpoint', default='')
    add('--checkpoint-dir', default='')
    add('--cross-dataset-eval', action='store_true', help='Evaluate a checkpoint on a different cohort. This skips only the exact training-observation support check; checkpoint method, feature count, and ordered var_names remain mandatory. Source cells remain restricted to the fitted checkpoint age domain, while inference may extrapolate.')
    add('--full-forward-cohort-eval', action='store_true', help='Use the complete foreign report cohort as both calibration targets and the strictly younger source bank. Requires cross-dataset checkpoint evaluation and a matched-source manifest.')
    add('--train-only', action='store_true')
    add('--min-normal-cells', type=int, default=100)
    add('--min-disease-cells', type=int, default=50)
    add('--max-eval-cells', type=int, default=5000)
    add('--max-eval-ref-cells', type=int, default=50000)
    add('--mmd-block-size', type=int, default=256)
    add('--max-sinkhorn-cells', type=int, default=2000)
    add('--projection-sinkhorn-blur', type=float, default=0.05)
    add('--projection-sinkhorn-scaling', type=float, default=0.5)
    add('--eval-source-policy', choices=['first_start', 'random_train_pool'], default='random_train_pool')
    add('--normal-holdout-fraction', type=float, default=0.2)
    add('--normal-holdout-max-donor-fraction', type=float, default=0.3)
    add('--min-calibration-cells', type=int, default=100)
    add('--normal-holdout-donors-file', default='')
    add('--calibration-only', action='store_true')
    add('--calibration-objective', choices=['projection', 'logfc'], default='projection')
    add('--also-calibration-projection', action='store_true')
    add('--calibration-targets', default='')
    add('--save-holdout-predictions', default='')
    add('--projection-min-age', type=float, default=None)
    add('--projection-max-age', type=float, default=None)
    add('--projection-age-step', type=float, default=1.0)
    add('--projection-age-window', type=float, default=float('inf'))
    add('--time-normalization', choices=['fit_minmax', 'age_100'], default='fit_minmax', help='Model-time coordinate; age_100 uses tau=chronological_age/100.')
    add('--unconstrained-age-search', action='store_true', help="Search candidate ages on both sides of each rollout source when the method's integrator supports reverse-time evaluation.")
    add('--rollout-source-policy', choices=['pooled_by_source_age'], default='pooled_by_source_age', help='Pool all eligible cells at each selected source age.')
    add('--rollout-source-ages-per-target', type=int, default=1)
    add('--random-source-ages-file', default='')
    add('--matched-source-ages-file', default='')
    add('--projection-source-aggregation', choices=['pooled_by_source_age'], default='pooled_by_source_age', help='Emit one prediction per pooled source age, matching FlowMap.')
    add('--cell-types', default='')
    add('--skip-existing', action='store_true')
    add('--overwrite', action='store_true')
    add('--seed', type=int, default=42)
    return parser
